    fun itemsFor(purposes: Set<Int>): List<Item> =
        all.filter { it.purpose == P_COMMON || purposes.contains(it.purpose) }

    // =========================================================
    // 評価
    // =========================================================
    fun evaluate(purposes: Set<Int>, checked: Set<String>): Report {
        val items = itemsFor(purposes)
        val max = items.sumOf { it.weight }
        val score = items.filter { checked.contains(it.id) }.sumOf { it.weight }
        val percent = if (max == 0) 0 else (score * 100 / max)
        val unchecked = items.filter { !checked.contains(it.id) }

        val musts = unchecked.filter { it.weight == W_MUST }
        val importants = unchecked.filter { it.weight == W_IMPORTANT }
        val recommends = unchecked.filter { it.weight == W_RECOMMEND }

        // 必須項目に穴があるうちはA評価にしない
        val grade = when {
            musts.size >= 3 -> "D（危険）"
            musts.isNotEmpty() -> "C（要対策）"
            importants.isEmpty() -> "A（良好）"
            percent >= 80 -> "B（要改善）"
            else -> "C（要対策）"
        }

        val summary = when {
            musts.size >= 3 ->
                "必須項目が${musts.size}件も未対応です。この状態で" +
                purposes.joinToString("・") { purposeName(it) } +
                "の用途に使うのは危険です。まず必須項目から着手してください。"
            musts.isNotEmpty() ->
                "全体としては進んでいますが、必須項目に${musts.size}件の穴があります。" +
                "ここが破られると他の対策が意味を失うため、最優先で対応してください。"
            importants.isNotEmpty() ->
                "必須項目はすべて対応済みです。重要項目${importants.size}件を埋めれば、" +
                "この用途で求められる水準に到達します。"
            recommends.isNotEmpty() ->
                "必須・重要項目はすべて対応済みで、良好な状態です。" +
                "残りは余裕があれば取り組む項目です。"
            else ->
                "全項目に対応できています。年1回は見直しを行い、" +
                "利用目的が変わったら再評価してください。"
        }

        return Report(score, max, percent, grade, musts, importants, recommends,
            items.size - unchecked.size, items.size, summary)
    }

