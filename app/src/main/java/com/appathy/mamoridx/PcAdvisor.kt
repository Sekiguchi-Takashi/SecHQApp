    // 保存
    // =========================================================
    fun loadOs(ctx: Context): Int =
        ctx.getSharedPreferences(PREF, Context.MODE_PRIVATE).getInt(K_OS, OS_WIN)

    fun saveOs(ctx: Context, os: Int) {
        ctx.getSharedPreferences(PREF, Context.MODE_PRIVATE).edit().putInt(K_OS, os).apply()
    }

    fun loadPurposes(ctx: Context): MutableSet<Int> {
        val raw = ctx.getSharedPreferences(PREF, Context.MODE_PRIVATE)
            .getString(K_PURPOSES, "") ?: ""
        return raw.split(',').mapNotNull { it.trim().toIntOrNull() }.toMutableSet()
    }

    fun savePurposes(ctx: Context, purposes: Set<Int>) {
        ctx.getSharedPreferences(PREF, Context.MODE_PRIVATE).edit()
            .putString(K_PURPOSES, purposes.joinToString(",")).apply()
    }

    fun loadChecked(ctx: Context): MutableSet<String> {
        val raw = ctx.getSharedPreferences(PREF, Context.MODE_PRIVATE)
            .getString(K_CHECKED, "") ?: ""
        return raw.split(',').filter { it.isNotBlank() }.toMutableSet()
    }

    fun saveChecked(ctx: Context, checked: Set<String>) {
        ctx.getSharedPreferences(PREF, Context.MODE_PRIVATE).edit()
            .putString(K_CHECKED, checked.joinToString(",")).apply()
    }
